/** A client op id for /api/export ops. getRandomValues, not randomUUID: Unsloth on a LAN
 *  address is not a secure context. */
export function newExportOpId(): string {
  return Array.from(crypto.getRandomValues(new Uint8Array(16)), (b) =>
    b.toString(16).padStart(2, "0"),
  ).join("");
}
